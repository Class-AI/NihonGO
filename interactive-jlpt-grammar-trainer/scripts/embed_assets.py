"""Embed every PWA image as base64 TEXT in src/lib/pwa-assets.ts.

Why: some upload/deploy paths silently drop binary files (PNG/ICO) but keep text files.
PWABuilder then sees 404 for every icon/screenshot. Text can't be dropped, and the routes
src/app/icons/[file], src/app/screenshots/[file] serve the images at the SAME URLs.

Source images live in scripts/assets-src/ (icons/, screenshots/, favicon.ico).
Run:  python3 scripts/embed_assets.py
"""
import base64, hashlib, io, os
from PIL import Image

SRC = "scripts/assets-src"
OUT = "src/lib/pwa-assets.ts"
items = {}

for sub in ("icons", "screenshots"):
    d = os.path.join(SRC, sub)
    for name in sorted(os.listdir(d)):
        path = os.path.join(d, name)
        im = Image.open(path)
        if sub == "screenshots":  # shrink file size (flat UI mock-ups) without changing pixel size
            im = im.convert("RGB").quantize(colors=192, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        buf = io.BytesIO()
        im.save(buf, "PNG", optimize=True)
        items[f"{sub}/{name}"] = buf.getvalue()

# favicon.ico (multi-size ICO)
base = Image.open(os.path.join(SRC, "icons", "icon-512.png")).convert("RGBA")
buf = io.BytesIO()
base.save(buf, "ICO", sizes=[(16, 16), (32, 32), (48, 48), (64, 64)])
items["icons/favicon.ico"] = buf.getvalue()

lines = ["// AUTO-GENERATED by scripts/embed_assets.py — do not edit by hand.", "export const PWA_ASSETS: Record<string, string> = {"]
for key, data in items.items():
    lines.append(f'  "{key}": "{base64.b64encode(data).decode()}",')
lines.append("};")
lines.append("")
lines.append("// sha256 of each decoded file (used by the verification script)")
lines.append("export const PWA_ASSET_SHA: Record<string, string> = {")
for key, data in items.items():
    lines.append(f'  "{key}": "{hashlib.sha256(data).hexdigest()}",')
lines.append("};")
open(OUT, "w").write("\n".join(lines) + "\n")
total = sum(len(v) for v in items.values())
print(f"embedded {len(items)} files, {total/1024:.0f} KB binary -> {os.path.getsize(OUT)/1024:.0f} KB text")
for k, v in items.items():
    print(f"  {k:36} {len(v)/1024:7.1f} KB")
